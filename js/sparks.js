const LS = 'tafiha.spark';

// tip, gain, tip, gain…; n is a running count kept on the device
export function sparkAt(n) {
  const gain = n % 2 === 1;
  const list = gain ? GAINS : TIPS;
  return { kind: gain ? 'gain' : 'tip', label: gain ? 'شو بتكسب' : 'نصيحة', text: list[Math.floor(n / 2) % list.length] };
}

export function loadSpark() {
  try { const n = Number(localStorage.getItem(LS)); return Number.isInteger(n) && n >= 0 ? n : 0; } catch { return 0; }
}

export function saveSpark(n) {
  try { localStorage.setItem(LS, String(n % (2 * TIPS.length * GAINS.length))); } catch { /* starts from the first next time */ }
}
